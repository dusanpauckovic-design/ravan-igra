const {chromium}=require(process.env.RAVAN_PLAYWRIGHT || 'playwright');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const fs=require('node:fs'),assert=require('node:assert/strict');
const [html,output]=process.argv.slice(2);
const root=path.resolve(output)+path.sep;
(async()=>{
const browser=await chromium.launch({executablePath:process.env.RAVAN_CHROMIUM,timeout:12000,args:['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--single-process','--no-zygote','--disable-gpu-sandbox']});
const p=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce',offline:true});
const errors=[],checks=[];
p.on('console',m=>{if(m.type()==='error'){errors.push(m.text());console.log(m.text().slice(0,1500));}});p.on('pageerror',e=>errors.push(e.message));
const snapshot=()=>p.evaluate(()=>window.ravanAudit?.());
const cdp=await p.context().newCDPSession(p);
const shot=async name=>{const img=await cdp.send('Page.captureScreenshot',{format:'png',fromSurface:true});fs.writeFileSync(root+name+'.png',Buffer.from(img.data,'base64'));};
const press=id=>p.locator(id).click({timeout:30000});
const check=(label,value)=>{assert.ok(value,label);checks.push(label);console.log(label);};
await p.goto(pathToFileURL(path.resolve(html)).href);
await p.waitForFunction(()=>document.documentElement.dataset.ready,undefined,{polling:250,timeout:55000});
await p.waitForTimeout(1400);
const original=await snapshot();
check('Offline WebGL 2 and MakeHuman GLB loaded',original?.webgl2&&original?.meshes['assets/putnik.glb'].triangles>1000);
check('Valley footprint 7.8x',Math.abs(original.bounds.x*original.bounds.z/72/63-7.8)<.01);
await shot('RAVAN_Prosirena_Dolina');
await press('#center');await press('#zoom-in');await press('#zoom-in');await press('#zoom-in');await press('#zoom-in');
await p.waitForTimeout(1600);await shot('RAVAN_Putnik_3D');
await press('#center');await press('#light');
await p.waitForTimeout(1600);
const fog=await snapshot();
check('Fog is anchored to traveler and conceals undiscovered destinations',fog.fog.enabled&&String(fog.fog.center)===String(fog.party)&&fog.fog.known.length<=2);
await shot('RAVAN_Magla_Istrazivanja');
await press('#quality');
const campX=fog.party[0];
await p.locator('#scene').click({position:{x:fog.nearby.x,y:fog.nearby.y}});
await p.waitForTimeout(1800);
const explored=await snapshot();
check('Nearby ground click moves traveler and fog centre',Math.abs(explored.party[0]-campX)>2&&String(explored.party)===String(explored.fog.center));
await press('#light');
await press('#overview');
await p.waitForTimeout(1200);await shot('RAVAN_Cela_Dolina');
await p.setViewportSize({width:390,height:844});
await press('#center');
await p.waitForTimeout(1300);
await shot('RAVAN_Dolina_Mobilni_V2');
check('Mobile destination picker and scene fit',await p.locator('#place-list').isVisible()&&await p.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
await p.locator('#place-list').selectOption('east');
await press('#travel');
await p.waitForTimeout(1200);
const east=await snapshot();
check('Routes reach expanded valley and reveal intervening locations',east.origin==='east'&&east.party[0]===104&&east.fog.known.includes('quarry'));
await p.emulateMedia({reducedMotion:'no-preference'});
await p.locator('#place-list').selectOption('spring');await press('#travel');
await p.waitForFunction(()=>window.ravanAudit().origin==='spring',undefined,{polling:500,timeout:45000});
const spring=await snapshot();
check('Animated journey reaches the outer spring',spring.party[0]===48&&spring.party[1]===136);
check('Zero browser and shader errors',errors.length===0);
fs.writeFileSync(root+'QA.json',JSON.stringify({browser:browser.version(),checks,errors,original,fog,explored,east,spring},null,2));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});

window.runRavanQA = async function(stage, check) {
  const ui=window.ravanSprint, $=ui.$;
  await ui.viewer.ready;
  if(stage>=16){
    check('zavrsna proba pocinje u druzini',ui.screens.get()==='party');
    document.querySelector('[data-screen=battle]').click();
  }
  const rect=$('arena').getBoundingClientRect(), actions=$('actions').getBoundingClientRect();
  check('tabla i akcije staju u viewport',rect.bottom<=innerHeight && actions.bottom<=innerHeight && document.documentElement.scrollWidth<=innerWidth);
  check('cilj susreta vidljiv',$('objective').textContent.includes('Tihog lovca'));
  document.querySelector('[data-unit=a_iva]').click();
  check('Iva selektovana, Radan ostaje aktivan',$('selection').textContent.includes('Iva') && $('turn').textContent.includes('Radan'));
  check('detalji zatvoreni na pocetku',!document.querySelector('details').open);
  $('view').click();
  const p=ui.viewer.project(ui.scene.units[0]), cell=ui.viewer.hitTest(p.x,p.y);
  check('2D preklop zadrzava hex',cell.x===3 && cell.y===3);
  $('view').click(); ui.reset();
  if(stage<8) return;
  const pick=(x,y)=>{
    const p=ui.viewer.project({x,y}), r=$('arena').getBoundingClientRect();
    $('arena').dispatchEvent(new MouseEvent('click',{clientX:r.left+p.x*r.width/960,clientY:r.top+p.y*r.height/570}));
  };
  $('attack').click(); pick(3,3);
  check('razlog blokade vidljiv',$('action-panel').textContent.includes('protivnika') && $('confirm').disabled);
  pick(4,3);
  check('pregled cene i ishoda',$('action-panel').textContent.includes('58 → 44') && $('action-panel').textContent.includes('Cena'));
  document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}));
  check('Escape otkazuje bez slanja',ui.actionPort.count()===0 && !$('confirm'));
  $('heal').click(); pick(3,3);
  check('lecenje prikazuje rezultat',$('action-panel').textContent.includes('64 → 76'));
  $('cancel-action').click(); $('move').click(); pick(2,4);
  check('kretanje prikazuje putanju',$('action-panel').textContent.includes('2 polja'));
  const confirmation=$('confirm');
  confirmation.click(); confirmation.click();
  for(let i=0;i<25&&ui.actionPanel.isPending();i++) await new Promise(r=>setTimeout(r,60));
  check('jedna potvrda, jedno slanje',ui.actionPort.count()===1 && ui.viewer.getSnapshot().units[0].y===4);
  ui.reset(); $('attack').click(); pick(4,3);
  if(stage<9) return;
  document.querySelector('[data-screen=party]').click();
  check('druzina prikazuje ulogu, oruzje i stanje',$('screen').textContent.includes('Dugi noz') && $('screen').textContent.includes('64/78'));
  document.querySelector('[data-party=a_iva]').click();
  check('Iva ima dva razlicita build efekta',document.querySelectorAll('[data-build]').length===2 && $('screen').textContent.includes('domet 6'));
  document.querySelector('[data-build=daleka]').click();
  await Promise.resolve();
  document.querySelector('[data-slot="1"]').click();
  document.querySelector('[data-technique=aim]').click();
  await Promise.resolve();
  check('build i drugi slot prihvaceni kroz port',ui.partyPort.get()[1].build==='daleka' && ui.partyPort.get()[1].slots[1]==='aim');
  check('tacno tri slota',document.querySelectorAll('[data-slot]').length===3);
  $('party-back').click();
  check('povratak u borbu bez izmene HP-a',!$('battle').hidden && ui.viewer.getSnapshot().units[0].hp===64);
  if(stage<10){document.querySelector('[data-screen=party]').click();return;}
  document.querySelector('[data-screen=skills]').click();
  document.querySelector('[data-skill=steady]').click();
  const before=ui.skillPort.points();
  check('zakljucan cvor prikazuje preduslov',$('screen').textContent.includes('Prvo nauci Daleki hitac') && $('learn').disabled);
  $('learn').click();
  check('zakljucan cvor ne trosi poene',ui.skillPort.points()===before);
  document.querySelector('[data-skill=longshot]').click();
  check('dostupan cvor ima stvaran efekat i cenu',$('screen').textContent.includes('+1 dometa')&&!$('learn').disabled);
  $('learn').click(); await Promise.resolve();
  check('learn trosi jedan poen i otkljucava sledeci cvor',ui.skillPort.points()===before-1 && ui.skillPort.status('steady').key==='open');
  document.querySelector('[data-skill=steady]').click();
  check('poeni i povratak ostaju vidljivi',$('skills-back').getBoundingClientRect().bottom<innerHeight);
  if(stage<11) return;
  $('skills-back').click();ui.reset();
  const mud=ui.viewer.describeCell({x:6,y:3});
  const cover=ui.viewer.describeCell({x:5,y:3});
  check('blato i prepreke razdvojeni u podacima',mud.kind==='mud'&&!mud.cover&&cover.cover.breakable&&cover.cover.hp===18);
  const beforeTerrain=JSON.stringify(ui.viewer.getSnapshot());
  $('terrain-compare').click();$('terrain-compare').click();
  check('pre/posle cuva celu geometriju i stanje',JSON.stringify(ui.viewer.getSnapshot())===beforeTerrain);
  const h=ui.viewer.project({x:6,y:4}), r=$('arena').getBoundingClientRect();
  $('arena').dispatchEvent(new MouseEvent('pointermove',{clientX:r.left+h.x*r.width/960,clientY:r.top+h.y*r.height/570}));
  check('hover imenuje blato',$('hex').textContent.includes('blato'));
  if(stage<12) return;
  $('figure-group').click();
  const order=ui.viewer.getDrawOrder();
  check('Iva se bira iza zaklona',order.indexOf('a_iva')<order.indexOf('zaklon') && $('selection').textContent.includes('Iva'));
  const pose=ui.viewer.project({x:5,y:2});
  $('figure-compare').click();
  const original=ui.viewer.project({x:5,y:2});
  $('figure-compare').click();
  check('uporedni prikaz zadrzava oslonac na istom heksu',pose.x===original.x && pose.y===original.y);
  check('sve tri uloge ostaju citljive',$('roster').textContent.includes('Zastitnik')&&$('roster').textContent.includes('Izvidjac')&&$('roster').textContent.includes('Ucenjak'));
  if(stage<13) return;
  const mode=name=>{ui.replay.speed.value=name;ui.replay.applySpeed();};
  const finished=[];
  for(const name of ['normal','fast','reduced']){
    mode(name);finished.push(await ui.replay.play());
    finished.push(JSON.stringify(ui.viewer.getSnapshot()));
  }
  check('tri brzine daju isto krajnje stanje',finished[0]==='complete' && finished[2]==='complete' && finished[4]==='complete' && finished[1]===finished[3] && finished[3]===finished[5]);
  check('kontakt i rusenje primenili dostavljene vrednosti',ui.viewer.getSnapshot().units[3].hp===0 && ui.viewer.getSnapshot().covers.find(c=>c.id==='zaklon').hp===0);
  mode('normal');const interrupted=ui.replay.play();
  await new Promise(r=>setTimeout(r,100));ui.reset();
  check('reset prekida sekvencu i brise efekte',await interrupted==='cancelled' && !ui.viewer.getPlayback().event && ui.viewer.getPlayback().seen===0);
  mode('fast');await ui.replay.play();
  document.querySelector('#battle details').open=true;
  if(stage<14)return;
  check('pobeda otvara rezime i jedan izbor',ui.screens.get()==='outcome' && $('claim-reward').disabled);
  check('nedostupna nagrada ima razlog',document.querySelector('[data-reward=gold]').disabled && $('screen').textContent.includes('nedostupna'));
  document.querySelector('[data-reward=wood]').click();
  const claim=$('claim-reward'), prior=ui.outcomePort.count();
  claim.click();claim.click();await Promise.resolve();
  check('nagrada se belezi jednom',ui.outcomePort.count()===prior+1 && ui.outcomePort.get().claimed==='wood');
  $('next-encounter').click();await Promise.resolve();
  check('sledeci susret otvara novi cilj',ui.screens.get()==='battle' && $('objective').textContent.includes('Divlju zver'));
  $('trial-defeat').click();
  check('poraz daje checkpoint bez nagrade',!!$('checkpoint')&&!$('claim-reward'));
  $('checkpoint').click();await Promise.resolve();
  if(stage>=16){
    check('checkpoint vraca pocetak aktuelnog susreta',ui.viewer.getSnapshot().units[3].hp===37 && $('arena-title').textContent==='Patrola doline');
    ui.loadEncounter('Kameni prolaz','Savladaj Tihog lovca.',ui.scene);
  }else check('checkpoint vraca pocetnu scenu',ui.viewer.getSnapshot().units[3].hp===58 && $('arena-title').textContent==='Kameni prolaz');
  ui.outcome.show('victory');
  if(stage<15)return;
  document.querySelector('[data-screen=battle]').click();ui.reset();
  $('attack').click();
  check('jedan savet trazi metu',$('hint').textContent.includes('Izaberi metu') && document.querySelectorAll('#hint').length===1);
  pick(3,3);
  check('blokada i dalje objasnjava razlog',$('hint').textContent.includes('razlog') && $('action-panel').textContent.includes('protivnika'));
  pick(4,3);
  check('savet za potvrdu i vazan rezultat su vidljivi bez zvuka',ui.hints.muted()&&$('hint').textContent.includes('Potvrdi')&&$('action-panel').textContent.includes('58 → 44'));
  $('skip-hints').click();
  check('pomoc se preskace bez blokiranja potvrde',$('hint').hidden && !$('confirm').disabled);
  $('hint-toggle').checked=true;$('hint-toggle').dispatchEvent(new Event('change'));
  check('pomoc se moze vratiti iz detalja',ui.hints.enabled()&&!$('hint').hidden);
  if(stage<16)return;
  const extended=ui.copy(ui.scene);
  extended.units[0].name='Radan Sa Veoma Dugackim Imenom Za Proveru';
  ui.reset(extended);
  const name=document.querySelector('[data-unit=a_radan] strong');
  check('dugacko ime zadrzava pun tekst i raspored',name.textContent===extended.units[0].name && name.scrollWidth>=name.clientWidth && document.documentElement.scrollWidth<=innerWidth);
  ui.reset();
  check('smanjeno kretanje i mute dostupni',ui.hints.muted() && !!Array.from(ui.replay.speed.options).find(o=>o.value==='reduced'));
  document.querySelector('[data-screen=party]').click();
  document.addEventListener('click',e=>{if(e.isTrusted)window.__trusted=(window.__trusted||0)+1;},true);
  document.addEventListener('keydown',e=>{if(e.isTrusted&&e.key==='Enter')window.__trustedEnter=(window.__trustedEnter||0)+1;},true);

};

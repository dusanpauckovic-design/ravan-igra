window.runRavanQA = async function(stage, check) {
  const ui=window.ravanSprint, $=ui.$;
  await ui.viewer.ready;
  const rect=$('arena').getBoundingClientRect(), actions=$('actions').getBoundingClientRect();
  check('tabla i akcije staju u viewport',rect.bottom<=innerHeight && actions.bottom<=innerHeight && document.documentElement.scrollWidth<=innerWidth);
  check('cilj susreta vidljiv',$('objective').textContent.includes('Tihog lovca'));
  document.querySelector('[data-unit=a_iva]').click();
  check('Iva selektovana, Radan ostaje aktivan',$('selection').textContent.includes('Iva') && $('turn').textContent.includes('Radan'));
  check('detalji zatvoreni na pocetku',!document.querySelector('details').open);
  $('view').click();
  const p=ui.viewer.project(ui.scene.units[0]), cell=ui.viewer.hitTest(p.x,p.y);
  check('2D preklop zadrzava hex',cell.x===3 && cell.y===3);
  $('view').click(); ui.reset();
  if(stage<8) return;
  const pick=(x,y)=>{
    const p=ui.viewer.project({x,y}), r=$('arena').getBoundingClientRect();
    $('arena').dispatchEvent(new MouseEvent('click',{clientX:r.left+p.x*r.width/960,clientY:r.top+p.y*r.height/570}));
  };
  $('attack').click(); pick(3,3);
  check('razlog blokade vidljiv',$('action-panel').textContent.includes('protivnika') && $('confirm').disabled);
  pick(4,3);
  check('pregled cene i ishoda',$('action-panel').textContent.includes('58 → 44') && $('action-panel').textContent.includes('Cena'));
  document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}));
  check('Escape otkazuje bez slanja',ui.actionPort.count()===0 && !$('confirm'));
  $('heal').click(); pick(3,3);
  check('lecenje prikazuje rezultat',$('action-panel').textContent.includes('64 → 76'));
  $('cancel-action').click(); $('move').click(); pick(2,4);
  check('kretanje prikazuje putanju',$('action-panel').textContent.includes('2 polja'));
  const confirmation=$('confirm');
  confirmation.click(); confirmation.click();
  for(let i=0;i<25&&ui.actionPanel.isPending();i++) await new Promise(r=>setTimeout(r,60));
  check('jedna potvrda, jedno slanje',ui.actionPort.count()===1 && ui.viewer.getSnapshot().units[0].y===4);
  ui.reset(); $('attack').click(); pick(4,3);
  if(stage<9) return;
  document.querySelector('[data-screen=party]').click();
  check('druzina prikazuje ulogu, oruzje i stanje',$('screen').textContent.includes('Dugi noz') && $('screen').textContent.includes('64/78'));
  document.querySelector('[data-party=a_iva]').click();
  check('Iva ima dva razlicita build efekta',document.querySelectorAll('[data-build]').length===2 && $('screen').textContent.includes('domet 6'));
  document.querySelector('[data-build=daleka]').click();
  await Promise.resolve();
  document.querySelector('[data-slot="1"]').click();
  document.querySelector('[data-technique=aim]').click();
  await Promise.resolve();
  check('build i drugi slot prihvaceni kroz port',ui.partyPort.get()[1].build==='daleka' && ui.partyPort.get()[1].slots[1]==='aim');
  check('tacno tri slota',document.querySelectorAll('[data-slot]').length===3);
  $('party-back').click();
  check('povratak u borbu bez izmene HP-a',!$('battle').hidden && ui.viewer.getSnapshot().units[0].hp===64);
  document.querySelector('[data-screen=party]').click();
};
